async function seedGujaratiArticlesAllCategories() {
  console.log("🚀 Starting insertion of authentic Gujarati articles for ALL categories...");

  // 1. Get or create Author
  let author = await prisma.author.findFirst();
  if (!author) {
    let user = await prisma.user.findFirst();
    if (!user) {
      user = await prisma.user.create({
        data: {
          email: 'bureau@gujaratpost.com',
          passwordHash: '$2a$10$abcdefghijklmnopqrstuuvwwxyz1234567890',
          role: 'SUPER_ADMIN',
          status: 'ACTIVE'
        }
      });
    }
    author = await prisma.author.create({
      data: {
        userId: user.id,
        name: 'Gujarat Post Bureau',
        nameGu: 'ગુજરાત પોસ્ટ બ્યુરો',
        nameHi: 'ગુજરાત પોસ્ટ બ્યુરો',
        image: '/assets/demo/1.jpg',
        designation: 'Editorial Bureau',
        designationGu: 'સંપાદકીય બ્યુરો',
        designationHi: 'સંપાદકીય બ્યુરો',
        bio: 'Official Editorial Bureau of Gujarat Post.',
        bioGu: 'ગુજરાત પોસ્ટનું સત્તાવાર સંપાદકીય બ્યુરો.',
        bioHi: 'ગુજરાત પોસ્ટનું સત્તાવાર સંપાદકીય બ્યુરો.'
      } as any
    });
  }

  // 2. Fetch all categories from MySQL Database
  const dbCategories = await prisma.category.findMany({ where: { isActive: true } });
  console.log(`📌 Found ${dbCategories.length} active categories in MySQL database.`);

  // 3. Find highest existing articleNumber
  const lastPostWithNumber = await prisma.post.findFirst({
    where: { articleNumber: { not: null } },
    orderBy: { articleNumber: 'desc' }
  });
  let nextArticleNumber = (lastPostWithNumber?.articleNumber || 500) + 1;

  let totalAdded = 0;

  for (const cat of dbCategories) {
    const slug = cat.slug;
    const articlesToAdd = CATEGORY_ARTICLES_GUJARATI[slug] || [
      {
        title: `${cat.nameGu} વિભાગમાં નવીનતમ તાજા સમાચાર અપડેટ`,
        excerpt: `${cat.nameGu} ક્ષેત્રમાં તાજેતરમાં બનેલી મહત્વપૂર્ણ ઘટનાઓ અને વિકાસ કાર્યો અંગેની વિગતો.`,
        content: `${cat.nameGu} ક્ષેત્રમાં વિવિધ વિકાસલક્ષી યોજનાઓ અને નાગરિક સેવાઓમાં મોટો સુધારો કરવામાં આવ્યો છે. તંત્ર દ્વારા ઝડપી અને પારદર્શી કામગીરી હાથ ધરવામાં આવી રહી છે, જેનાથી સ્થાનિક નાગરિકોને સીધો ફાયદો થશે.`,
        image: '/assets/demo/1.jpg',
        location: cat.nameGu
      },
      {
        title: `${cat.nameGu}: નવી યોજનાઓ અને પ્રજાલક્ષી કાર્યોની સમીક્ષા`,
        excerpt: `${cat.nameGu}માં હાથ ધરાયેલા માળખાકીય સુવિધાઓના કામો અંગે વરિષ્ઠ અધિકારીઓએ સ્થળ તપાસ કરી.`,
        content: `${cat.nameGu} વિસ્તારના સર્વાંગી વિકાસ માટે તંત્ર દ્વારા નવા પ્રોજેક્ટ્સ મંજૂર કરવામાં આવ્યા છે. માર્ગો, સફાઈ અને ડિજિટલ સેવાઓનું વિસ્તરણ કરીને નાગરિકોની સુવિધામાં વધારો કરવામાં આવી રહ્યો છે.`,
        image: '/assets/demo/2.jpg',
        location: cat.nameGu
      }
    ];

    console.log(`📝 Processing category: ${cat.nameGu} (${slug}) - Adding ${articlesToAdd.length} Gujarati articles...`);

    for (let idx = 0; idx < articlesToAdd.length; idx++) {
      const art = articlesToAdd[idx];
      const uniqueSlug = `${slug}-${Date.now()}-${idx + 1}-${Math.floor(Math.random() * 1000)}`;

      await prisma.post.create({
        data: {
          slug: uniqueSlug,
          articleNumber: nextArticleNumber++,
          language: 'gu',
          title: art.title,
          titleGu: art.title,
          titleHi: art.title,
          excerpt: art.excerpt,
          excerptGu: art.excerpt,
          excerptHi: art.excerpt,
          content: art.content,
          contentGu: art.content,
          contentHi: art.content,
          featuredImage: art.image,
          status: PostStatus.PUBLISHED,
          authorId: author.id,
          categoryId: cat.id,
          location: art.location || 'Gujarat',
          readingTime: 3,
          isTrending: art.isTrending || false,
          isBreaking: art.isBreaking || false,
          isFeatured: art.isFeatured || false,
          views: Math.floor(Math.random() * 800) + 120,
          createdAt: new Date(Date.now() - (totalAdded * 1000 * 60 * 15)), // Stagger timestamps
        }
      });

      totalAdded++;
    }
  }

  console.log(`✅ SUCCESS! Total ${totalAdded} authentic Gujarati articles added across ALL ${dbCategories.length} categories!`);
}

seedGujaratiArticlesAllCategories()
  .catch((e) => {
    console.error("❌ Error seeding Gujarati articles:", e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
